    CONSTRAINT ck_compta_ref_modele CHECK (modele IN ('NORMAL', 'SIMPLIFIE')),
    CONSTRAINT ck_compta_ref_numero CHECK (numero ~ '^[1-8][0-9]{1,11}$'),
    CONSTRAINT ck_compta_ref_classe CHECK (classe BETWEEN 1 AND 8),
    CONSTRAINT ck_compta_ref_sens CHECK (sens_normal IN ('DEBIT', 'CREDIT')),
