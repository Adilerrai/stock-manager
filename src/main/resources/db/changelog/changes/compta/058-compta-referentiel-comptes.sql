    modele            VARCHAR(10)  NOT NULL DEFAULT 'NORMAL',
    numero            VARCHAR(12)  NOT NULL,
    libelle           VARCHAR(255) NOT NULL,
    classe            SMALLINT     NOT NULL,
    rubrique          VARCHAR(2)   NOT NULL,
    sens_normal       VARCHAR(6)   NOT NULL,
